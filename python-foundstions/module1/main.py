# dynamically typed language

name = "Akhil" # string
age = 23 # int
height = 5.11 # float
is_working = False # bool

# type annotations like statically typed languages , unnecessary bt very useful and important .
name2: str = "Tron"
age2 : int = 90
height2: float = 6.0
is_working2 : bool = True

print(name , age , height, is_working)

print(f"{name2} {age2} {height2} {is_working2} ") # fstrings very useful
